//! OpenPBR and Autodesk Standard Surface MaterialX (v1.39) document generation.
//! Produces XML documents specifying standard surface shading graphs for Unreal, Blender, and USD.

use crate::material::PbrChannel;
use std::collections::BTreeMap;

/// Target surface shader model.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ShaderModel {
    StandardSurface,
    OpenPbr,
}

/// Normal map green channel direction.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NormalConvention {
    DirectX,
    OpenGl,
}

#[derive(Clone, Debug)]
pub struct MaterialXOptions {
    pub shader: ShaderModel,
    pub normal: NormalConvention,
    pub tiling: [f32; 2],
    pub displacement: bool,
    pub displacement_scale: f32,
}

impl Default for MaterialXOptions {
    fn default() -> Self {
        Self {
            shader: ShaderModel::OpenPbr,
            normal: NormalConvention::DirectX,
            tiling: [1.0, 1.0],
            displacement: false,
            displacement_scale: 1.0,
        }
    }
}

fn safe_identifier(s: &str) -> String {
    let mut out: String = s
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    while out.contains("__") {
        out = out.replace("__", "_");
    }
    let trimmed = out.trim_matches('_').to_string();
    if trimmed.is_empty() {
        "Material".to_string()
    } else if trimmed.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        format!("M_{trimmed}")
    } else {
        trimmed
    }
}

fn escape_xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// Generates a complete MaterialX 1.39 XML document connecting maps to a surface shader.
pub fn generate_materialx_document(
    name: &str,
    maps: &BTreeMap<PbrChannel, String>,
    options: &MaterialXOptions,
) -> String {
    let safe_name = safe_identifier(name);
    let mut doc = String::new();
    doc.push_str("<?xml version=\"1.0\"?>\n");
    doc.push_str("<materialx version=\"1.39\" colorspace=\"lin_rec709\">\n");
    doc.push_str("  <!-- Generated by hypermedia surface-pbr-studio -->\n");

    let nodegraph_name = format!("NG_{safe_name}");
    doc.push_str(&format!("  <nodegraph name=\"{nodegraph_name}\">\n"));
    doc.push_str("    <texcoord name=\"uv0\" type=\"vector2\">\n");
    doc.push_str("      <input name=\"index\" type=\"integer\" value=\"0\" />\n");
    doc.push_str("    </texcoord>\n");

    let tiling_str = format!("{:.3}, {:.3}", options.tiling[0], options.tiling[1]);

    let add_image = |d: &mut String, ch: PbrChannel, ty: &str, node_name: &str| {
        if let Some(file) = maps.get(&ch) {
            d.push_str(&format!("    <tiledimage name=\"{node_name}\" type=\"{ty}\">\n"));
            let cs = if matches!(ch, PbrChannel::BaseColor | PbrChannel::Emissive) {
                " colorspace=\"srgb_texture\""
            } else {
                ""
            };
            d.push_str(&format!(
                "      <input name=\"file\" type=\"filename\" value=\"{}\"{cs} />\n",
                escape_xml(file)
            ));
            d.push_str("      <input name=\"texcoord\" type=\"vector2\" nodename=\"uv0\" />\n");
            d.push_str(&format!(
                "      <input name=\"uvtiling\" type=\"vector2\" value=\"{tiling_str}\" />\n"
            ));
            d.push_str("    </tiledimage>\n");
        }
    };

    add_image(&mut doc, PbrChannel::BaseColor, "color3", "img_basecolor");
    add_image(&mut doc, PbrChannel::Roughness, "float", "img_roughness");
    add_image(&mut doc, PbrChannel::Metallic, "float", "img_metallic");
    add_image(&mut doc, PbrChannel::Normal, "vector3", "img_normal");
    add_image(&mut doc, PbrChannel::Height, "float", "img_height");
    add_image(&mut doc, PbrChannel::AO, "float", "img_ao");
    add_image(&mut doc, PbrChannel::Emissive, "color3", "img_emissive");
    add_image(&mut doc, PbrChannel::Opacity, "float", "img_opacity");

    if maps.contains_key(&PbrChannel::Normal) {
        doc.push_str("    <normalmap name=\"node_normal\" type=\"vector3\">\n");
        doc.push_str("      <input name=\"in\" type=\"vector3\" nodename=\"img_normal\" />\n");
        doc.push_str("      <input name=\"scale\" type=\"float\" value=\"1.0\" />\n");
        doc.push_str("    </normalmap>\n");
    }

    if maps.contains_key(&PbrChannel::BaseColor) {
        doc.push_str("    <output name=\"base_color_out\" type=\"color3\" nodename=\"img_basecolor\" />\n");
    }
    if maps.contains_key(&PbrChannel::Roughness) {
        doc.push_str("    <output name=\"roughness_out\" type=\"float\" nodename=\"img_roughness\" />\n");
    }
    if maps.contains_key(&PbrChannel::Metallic) {
        doc.push_str("    <output name=\"metallic_out\" type=\"float\" nodename=\"img_metallic\" />\n");
    }
    if maps.contains_key(&PbrChannel::Normal) {
        doc.push_str("    <output name=\"normal_out\" type=\"vector3\" nodename=\"node_normal\" />\n");
    }
    if maps.contains_key(&PbrChannel::AO) {
        doc.push_str("    <output name=\"ao_out\" type=\"float\" nodename=\"img_ao\" />\n");
    }
    if maps.contains_key(&PbrChannel::Emissive) {
        doc.push_str("    <output name=\"emissive_out\" type=\"color3\" nodename=\"img_emissive\" />\n");
    }

    doc.push_str("  </nodegraph>\n");

    // Surface shader node
    let shader_name = format!("SR_{safe_name}");
    match options.shader {
        ShaderModel::OpenPbr => {
            doc.push_str(&format!("  <open_pbr_surface name=\"{shader_name}\" type=\"surfaceshader\">\n"));
            doc.push_str("    <input name=\"base_weight\" type=\"float\" value=\"1.0\" />\n");
            if maps.contains_key(&PbrChannel::BaseColor) {
                doc.push_str(&format!("    <input name=\"base_color\" type=\"color3\" nodegraph=\"{nodegraph_name}\" output=\"base_color_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Roughness) {
                doc.push_str(&format!("    <input name=\"specular_roughness\" type=\"float\" nodegraph=\"{nodegraph_name}\" output=\"roughness_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Metallic) {
                doc.push_str(&format!("    <input name=\"base_metalness\" type=\"float\" nodegraph=\"{nodegraph_name}\" output=\"metallic_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Normal) {
                doc.push_str(&format!("    <input name=\"geometry_normal\" type=\"vector3\" nodegraph=\"{nodegraph_name}\" output=\"normal_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Emissive) {
                doc.push_str(&format!("    <input name=\"emission_color\" type=\"color3\" nodegraph=\"{nodegraph_name}\" output=\"emissive_out\" />\n"));
            }
            doc.push_str("  </open_pbr_surface>\n");
        }
        ShaderModel::StandardSurface => {
            doc.push_str(&format!("  <standard_surface name=\"{shader_name}\" type=\"surfaceshader\">\n"));
            doc.push_str("    <input name=\"base\" type=\"float\" value=\"1.0\" />\n");
            if maps.contains_key(&PbrChannel::BaseColor) {
                doc.push_str(&format!("    <input name=\"base_color\" type=\"color3\" nodegraph=\"{nodegraph_name}\" output=\"base_color_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Roughness) {
                doc.push_str(&format!("    <input name=\"specular_roughness\" type=\"float\" nodegraph=\"{nodegraph_name}\" output=\"roughness_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Metallic) {
                doc.push_str(&format!("    <input name=\"metalness\" type=\"float\" nodegraph=\"{nodegraph_name}\" output=\"metallic_out\" />\n"));
            }
            if maps.contains_key(&PbrChannel::Normal) {
                doc.push_str(&format!("    <input name=\"normal\" type=\"vector3\" nodegraph=\"{nodegraph_name}\" output=\"normal_out\" />\n"));
            }
            doc.push_str("  </standard_surface>\n");
        }
    }

    // Material node
    let mat_name = format!("M_{safe_name}");
    doc.push_str(&format!("  <surfacematerial name=\"{mat_name}\" type=\"material\">\n"));
    doc.push_str(&format!("    <input name=\"surfaceshader\" type=\"surfaceshader\" nodename=\"{shader_name}\" />\n"));
    doc.push_str("  </surfacematerial>\n");
    doc.push_str("</materialx>\n");

    doc
}
