//! Nastran Bulk Data File (.bdf) exporter.
//!
//! Grounded in open engineering data interchange and auditability (UDHR Art. 19, 27).

use crate::mesh::tet::Point3D;

/// Export to 8-field small-field Nastran BDF format.
pub fn export_nastran_bdf(
    nodes: &[Point3D],
    hex_elements: &[[usize; 8]],
    youngs_modulus: f64,
    poissons_ratio: f64,
    density: f64,
) -> String {
    let mut out = String::new();
    out.push_str("$\n$ NASTRAN INPUT DECK GENERATED BY CONTINUUM MULTIPHYSICS\n$\n");
    out.push_str("BEGIN BULK\n");

    for (i, p) in nodes.iter().enumerate() {
        out.push_str(&format!(
            "GRID    {:8}        {:8.3}{:8.3}{:8.3}\n",
            i + 1,
            p.x,
            p.y,
            p.z
        ));
    }

    for (i, el) in hex_elements.iter().enumerate() {
        out.push_str(&format!(
            "CHEXA   {:8}{:8}{:8}{:8}{:8}{:8}+\n+       {:8}{:8}{:8}\n",
            i + 1,
            1, // PID
            el[0] + 1,
            el[1] + 1,
            el[2] + 1,
            el[3] + 1,
            el[4] + 1,
            el[5] + 1,
            el[6] + 1,
        ));
    }

    out.push_str("PSOLID         1       1\n");
    out.push_str(&format!(
        "MAT1           1{:8.2e}        {:8.3}{:8.3}\n",
        youngs_modulus, poissons_ratio, density
    ));
    out.push_str("ENDDATA\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nastran_deck_contains_bulk_and_grid() {
        let nodes = [Point3D::new(0.0, 0.0, 0.0)];
        let hex = [[0; 8]];
        let bdf = export_nastran_bdf(&nodes, &hex, 200e9, 0.3, 7850.0);
        assert!(bdf.contains("BEGIN BULK"));
        assert!(bdf.contains("GRID"));
        assert!(bdf.contains("ENDDATA"));
    }
}
