//! LS-DYNA keyword deck (.k) exporter.
//!
//! Grounded in open engineering data interchange and auditability (UDHR Art. 19, 27).

use crate::mesh::tet::Point3D;

/// Export to LS-DYNA `.k` format.
pub fn export_lsdyna_k(
    nodes: &[Point3D],
    hex_elements: &[[usize; 8]],
    youngs_modulus: f64,
    poissons_ratio: f64,
    density: f64,
) -> String {
    let mut out = String::new();
    out.push_str("*KEYWORD\n$ LS-DYNA DECK GENERATED BY CONTINUUM MULTIPHYSICS\n");
    out.push_str("*NODE\n");
    for (i, p) in nodes.iter().enumerate() {
        out.push_str(&format!("{:8}{:16.6}{:16.6}{:16.6}\n", i + 1, p.x, p.y, p.z));
    }

    out.push_str("*ELEMENT_SOLID\n");
    for (i, el) in hex_elements.iter().enumerate() {
        out.push_str(&format!(
            "{:8}{:8}{:8}{:8}{:8}{:8}{:8}{:8}{:8}{:8}\n",
            i + 1,
            1, // PID
            el[0] + 1,
            el[1] + 1,
            el[2] + 1,
            el[3] + 1,
            el[4] + 1,
            el[5] + 1,
            el[6] + 1,
            el[7] + 1
        ));
    }

    out.push_str("*PART\nSolid Part\n       1       1       1\n");
    out.push_str("*SECTION_SOLID\n       1       1\n");
    out.push_str("*MAT_ELASTIC\n");
    out.push_str(&format!(
        "       1{:10.3e}{:10.3e}{:10.3}\n",
        density, youngs_modulus, poissons_ratio
    ));
    out.push_str("*END\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lsdyna_deck_structure() {
        let nodes = [Point3D::new(0.0, 0.0, 0.0)];
        let hex = [[0; 8]];
        let k = export_lsdyna_k(&nodes, &hex, 210e9, 0.3, 7850.0);
        assert!(k.contains("*KEYWORD"));
        assert!(k.contains("*ELEMENT_SOLID"));
        assert!(k.contains("*END"));
    }
}
