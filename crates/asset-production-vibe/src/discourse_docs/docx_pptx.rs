use super::*;
use crate::*;
use std::collections::BTreeMap;
use std::fmt::Write;

struct PptxSlideSpec {
    title: String,
    bullets: Vec<String>,
}

impl AssetHost<'_> {
    // ------------------------------------------------------------------------
    // 2. OpenXML Prose Document (.docx) Compilation
    // ------------------------------------------------------------------------
    pub(super) fn compile_prose_docx(&mut self, a: &Args) -> Result<Value, String> {
        fields(
            a,
            &[
                "title",
                "sections",
                "paragraphs",
                "table",
                "body",
                "artifact_id",
                "id",
            ],
        )?;

        let title = a
            .get("title")
            .map(text)
            .transpose()?
            .unwrap_or("Hypermedia Prose Document");

        let mut paragraph_count = 1usize; // Title paragraph
        let mut body_xml = String::new();

        // Title paragraph
        let _ = write!(
            body_xml,
            "<w:p><w:pPr><w:pStyle w:val=\"Title\"/><w:jc w:val=\"left\"/></w:pPr><w:r><w:rPr><w:b/><w:sz w:val=\"48\"/><w:color w:val=\"1E293B\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
            escape_xml(title)
        );

        if let Some(sec_val) = a.get("sections").or_else(|| a.get("paragraphs")) {
            for item in list(sec_val)? {
                match item {
                    Value::String(s) => {
                        let _ = write!(
                            body_xml,
                            "<w:p><w:r><w:rPr><w:sz w:val=\"22\"/><w:color w:val=\"334155\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
                            escape_xml(s)
                        );
                        paragraph_count += 1;
                    }
                    Value::Record(r) => {
                        if let Some(h) = r.get("heading").or_else(|| r.get("title")) {
                            if let Ok(ht) = text(h) {
                                let _ = write!(
                                    body_xml,
                                    "<w:p><w:pPr><w:pStyle w:val=\"Heading1\"/></w:pPr><w:r><w:rPr><w:b/><w:sz w:val=\"32\"/><w:color w:val=\"0F172A\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
                                    escape_xml(ht)
                                );
                                paragraph_count += 1;
                            }
                        }
                        if let Some(b) = r.get("body").or_else(|| r.get("text")).or_else(|| r.get("content")) {
                            if let Ok(bt) = text(b) {
                                let _ = write!(
                                    body_xml,
                                    "<w:p><w:r><w:rPr><w:sz w:val=\"22\"/><w:color w:val=\"334155\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
                                    escape_xml(bt)
                                );
                                paragraph_count += 1;
                            }
                        }
                    }
                    _ => {}
                }
            }
        } else if let Some(body_str) = a.get("body").map(text).transpose()? {
            for line in body_str.lines() {
                let _ = write!(
                    body_xml,
                    "<w:p><w:r><w:rPr><w:sz w:val=\"22\"/><w:color w:val=\"334155\"/></w:rPr><w:t>{}</w:t></w:r></w:p>",
                    escape_xml(line)
                );
                paragraph_count += 1;
            }
        } else {
            let _ = write!(
                body_xml,
                "<w:p><w:r><w:rPr><w:sz w:val=\"22\"/><w:color w:val=\"334155\"/></w:rPr><w:t>Generated by Hypermedia Discourse Ontology.</w:t></w:r></w:p>"
            );
            paragraph_count += 1;
        }

        // Optional table
        if let Some(tbl_val) = a.get("table") {
            let rows = list(tbl_val)?;
            if !rows.is_empty() {
                body_xml.push_str("<w:tbl><w:tblPr><w:tblStyle w:val=\"TableGrid\"/><w:tblW w:w=\"0\" w:type=\"auto\"/><w:tblBorders><w:top w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"CBD5E1\"/><w:left w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"CBD5E1\"/><w:bottom w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"CBD5E1\"/><w:right w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"CBD5E1\"/><w:insideH w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"E2E8F0\"/><w:insideV w:val=\"single\" w:sz=\"4\" w:space=\"0\" w:color=\"E2E8F0\"/></w:tblBorders></w:tblPr>");
                for row in rows {
                    let cells = list(row)?;
                    body_xml.push_str("<w:tr>");
                    for cell in cells {
                        let cell_txt = match cell {
                            Value::String(s) => s.as_str(),
                            _ => "",
                        };
                        let _ = write!(
                            body_xml,
                            "<w:tc><w:tcPr><w:tcW w:w=\"2400\" w:type=\"dxa\"/></w:tcPr><w:p><w:r><w:rPr><w:sz w:val=\"20\"/></w:rPr><w:t>{}</w:t></w:r></w:p></w:tc>",
                            escape_xml(cell_txt)
                        );
                    }
                    body_xml.push_str("</w:tr>");
                }
                body_xml.push_str("</w:tbl>");
            }
        }

        let document_xml = format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<w:document xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\">\n  <w:body>\n    {}\n    <w:sectPr><w:pgSz w:w=\"12240\" w:h=\"15840\"/><w:pgMar w:top=\"1440\" w:right=\"1440\" w:bottom=\"1440\" w:left=\"1440\"/></w:sectPr>\n  </w:body>\n</w:document>",
            body_xml
        );

        let content_types_xml = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">\n  <Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>\n  <Default Extension=\"xml\" ContentType=\"application/xml\"/>\n  <Override PartName=\"/word/document.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml\"/>\n</Types>";

        let rels_xml = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\n  <Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"word/document.xml\"/>\n</Relationships>";

        let mut zip = ZipArchiveWriter::new();
        zip.add_file("[Content_Types].xml", content_types_xml.as_bytes().to_vec());
        zip.add_file("_rels/.rels", rels_xml.as_bytes().to_vec());
        zip.add_file("word/document.xml", document_xml.into_bytes());

        let zip_bytes = zip.finish();
        let byte_len = zip_bytes.len();
        self.charge(paragraph_count * 512 + 512, byte_len * 2 + 1024)?;

        let encoded = self.encode("docx", zip_bytes)?;

        let mut rec = match encoded {
            Value::Record(r) => r,
            _ => BTreeMap::new(),
        };

        let id_str = a
            .get("artifact_id")
            .or_else(|| a.get("id"))
            .and_then(|v| text(v).ok())
            .map(|s| s.to_string())
            .unwrap_or_else(|| {
                let h = rec
                    .get("handle")
                    .and_then(|v| match v {
                        Value::U64(n) => Some(*n),
                        Value::I64(n) => Some(*n as u64),
                        _ => None,
                    })
                    .unwrap_or(0);
                format!("discourse-docx-{h}")
            });

        rec.insert("id".into(), Value::String(id_str.clone()));
        rec.insert("resource".into(), Value::String(id_str));
        rec.insert("kind".into(), Value::String("docx".into()));
        rec.insert("paragraph_count".into(), Value::I64(paragraph_count as i64));
        rec.insert("byte_len".into(), Value::I64(byte_len as i64));

        Ok(Value::Record(rec))
    }

    // ------------------------------------------------------------------------
    // 3. OpenXML Presentation Deck (.pptx) Compilation
    // ------------------------------------------------------------------------
    pub(super) fn compile_deck_pptx(&mut self, a: &Args) -> Result<Value, String> {
        fields(
            a,
            &["title", "subtitle", "slides", "body", "artifact_id", "id"],
        )?;

        let title = a
            .get("title")
            .map(text)
            .transpose()?
            .unwrap_or("Hypermedia Presentation Deck");

        let mut slides: Vec<PptxSlideSpec> = Vec::new();

        if let Some(slides_val) = a.get("slides") {
            let slide_items = list(slides_val)?;
            if slide_items.is_empty() {
                return Err("slides array must not be empty".into());
            }
            if slide_items.len() > 128 {
                return Err("slides count exceeds 128".into());
            }
            for (idx, item) in slide_items.iter().enumerate() {
                let r = record(item)?;
                let s_title = r
                    .get("title")
                    .map(text)
                    .transpose()?
                    .unwrap_or(&format!("Slide {}", idx + 1))
                    .to_string();

                let mut bullets = Vec::new();
                if let Some(bullets_val) = r.get("bullets") {
                    for b in list(bullets_val)? {
                        if let Ok(t) = text(b) {
                            bullets.push(t.to_string());
                        }
                    }
                } else if let Some(b_str) = r
                    .get("subtitle")
                    .or_else(|| r.get("body"))
                    .or_else(|| r.get("content"))
                    .map(text)
                    .transpose()?
                {
                    bullets.push(b_str.to_string());
                }

                slides.push(PptxSlideSpec {
                    title: s_title,
                    bullets,
                });
            }
        } else {
            // Default 1 slide
            let mut bullets = Vec::new();
            if let Some(sub) = a.get("subtitle").map(text).transpose()? {
                bullets.push(sub.to_string());
            } else if let Some(body) = a.get("body").map(text).transpose()? {
                bullets.push(body.to_string());
            } else {
                bullets.push("Generated by Hypermedia Discourse Foliation Engine.".to_string());
            }

            slides.push(PptxSlideSpec {
                title: title.to_string(),
                bullets,
            });
        }

        let slide_count = slides.len();

        let mut zip = ZipArchiveWriter::new();

        // 1. [Content_Types].xml
        let mut ct_xml = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\">\n  <Default Extension=\"rels\" ContentType=\"application/vnd.openxmlformats-package.relationships+xml\"/>\n  <Default Extension=\"xml\" ContentType=\"application/xml\"/>\n  <Override PartName=\"/ppt/presentation.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml\"/>\n");
        for i in 1..=slide_count {
            let _ = write!(
                ct_xml,
                "  <Override PartName=\"/ppt/slides/slide{i}.xml\" ContentType=\"application/vnd.openxmlformats-officedocument.presentationml.slide+xml\"/>\n"
            );
        }
        ct_xml.push_str("</Types>");
        zip.add_file("[Content_Types].xml", ct_xml.into_bytes());

        // 2. _rels/.rels
        let root_rels = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\n  <Relationship Id=\"rId1\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument\" Target=\"ppt/presentation.xml\"/>\n</Relationships>";
        zip.add_file("_rels/.rels", root_rels.as_bytes().to_vec());

        // 3. ppt/presentation.xml
        let mut pres_xml = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<p:presentation xmlns:p=\"http://schemas.openxmlformats.org/presentationml/2006/main\" xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\" xmlns:a=\"http://schemas.openxmlformats.org/drawingml/2006/main\">\n  <p:sldIdLst>\n");
        for i in 1..=slide_count {
            let _ = write!(pres_xml, "    <p:sldId id=\"{}\" r:id=\"rId{i}\"/>\n", 255 + i);
        }
        pres_xml.push_str("  </p:sldIdLst>\n  <p:sldSz cx=\"9144000\" cy=\"5143500\"/>\n</p:presentation>");
        zip.add_file("ppt/presentation.xml", pres_xml.into_bytes());

        // 4. ppt/_rels/presentation.xml.rels
        let mut pres_rels = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\n");
        for i in 1..=slide_count {
            let _ = write!(
                pres_rels,
                "  <Relationship Id=\"rId{i}\" Type=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide\" Target=\"slides/slide{i}.xml\"/>\n"
            );
        }
        pres_rels.push_str("</Relationships>");
        zip.add_file("ppt/_rels/presentation.xml.rels", pres_rels.into_bytes());

        // 5. ppt/slides/slide{i}.xml
        for (i, slide) in slides.iter().enumerate() {
            let slide_num = i + 1;
            let mut bullets_xml = String::new();
            for b in &slide.bullets {
                let _ = write!(
                    bullets_xml,
                    "<a:p><a:pPr lvl=\"0\"/><a:r><a:rPr lang=\"en-US\" sz=\"2000\"><a:solidFill><a:srgbClr val=\"334155\"/></a:solidFill></a:rPr><a:t>{}</a:t></a:r></a:p>",
                    escape_xml(b)
                );
            }

            let sld_xml = format!(
                "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<p:sld xmlns:p=\"http://schemas.openxmlformats.org/presentationml/2006/main\" xmlns:a=\"http://schemas.openxmlformats.org/drawingml/2006/main\" xmlns:r=\"http://schemas.openxmlformats.org/officeDocument/2006/relationships\">\n  <p:cSld>\n    <p:spTree>\n      <p:nvGrpSpPr><p:cNvPr id=\"1\" name=\"\"/><p:cNvGrpSpPr/><p:grpSpPr/></p:nvGrpSpPr>\n      <p:grpSpPr/>\n      <p:sp>\n        <p:nvSpPr><p:cNvPr id=\"2\" name=\"Title\"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>\n        <p:spPr><a:xfrm><a:off x=\"685800\" y=\"548640\"/><a:ext cx=\"7772400\" cy=\"914400\"/></a:xfrm></p:spPr>\n        <p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang=\"en-US\" sz=\"3600\" b=\"1\"><a:solidFill><a:srgbClr val=\"0F172A\"/></a:solidFill></a:rPr><a:t>{}</a:t></a:r></a:p></p:txBody>\n      </p:sp>\n      <p:sp>\n        <p:nvSpPr><p:cNvPr id=\"3\" name=\"Content\"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>\n        <p:spPr><a:xfrm><a:off x=\"685800\" y=\"1600200\"/><a:ext cx=\"7772400\" cy=\"3000000\"/></a:xfrm></p:spPr>\n        <p:txBody><a:bodyPr/><a:lstStyle/>{}</p:txBody>\n      </p:sp>\n    </p:spTree>\n  </p:cSld>\n</p:sld>",
                escape_xml(&slide.title),
                bullets_xml
            );

            zip.add_file(&format!("ppt/slides/slide{slide_num}.xml"), sld_xml.into_bytes());
        }

        let zip_bytes = zip.finish();
        let byte_len = zip_bytes.len();
        self.charge(slide_count * 1024 + 512, byte_len * 2 + 1024)?;

        let encoded = self.encode("pptx", zip_bytes)?;

        let mut rec = match encoded {
            Value::Record(r) => r,
            _ => BTreeMap::new(),
        };

        let id_str = a
            .get("artifact_id")
            .or_else(|| a.get("id"))
            .and_then(|v| text(v).ok())
            .map(|s| s.to_string())
            .unwrap_or_else(|| {
                let h = rec
                    .get("handle")
                    .and_then(|v| match v {
                        Value::U64(n) => Some(*n),
                        Value::I64(n) => Some(*n as u64),
                        _ => None,
                    })
                    .unwrap_or(0);
                format!("discourse-pptx-{h}")
            });

        rec.insert("id".into(), Value::String(id_str.clone()));
        rec.insert("resource".into(), Value::String(id_str));
        rec.insert("kind".into(), Value::String("pptx".into()));
        rec.insert("slide_count".into(), Value::I64(slide_count as i64));
        rec.insert("byte_len".into(), Value::I64(byte_len as i64));

        Ok(Value::Record(rec))
    }
}
