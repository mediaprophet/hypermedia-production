//! Labels and keys used by MXF (SMPTE RP 224 / RP 210, ST 377-1, ST 379-2).

pub fn set_key(kind: u8) -> [u8; 16] {
    [
        0x06, 0x0E, 0x2B, 0x34, 0x02, 0x53, 0x01, 0x01, 0x0D, 0x01, 0x01, 0x01, 0x01, 0x01, kind,
        0x00,
    ]
}

pub fn partition_key(kind: u8, status: u8) -> [u8; 16] {
    [
        0x06, 0x0E, 0x2B, 0x34, 0x02, 0x05, 0x01, 0x01, 0x0D, 0x01, 0x02, 0x01, 0x01, kind,
        status, 0x00,
    ]
}

