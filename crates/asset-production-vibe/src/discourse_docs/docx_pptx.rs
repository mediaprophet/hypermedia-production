use super::*;
use crate::*;
use chronicle_office_codecs::{
    parse_docx_package, parse_pptx_package, to_docx_package, to_pptx_package, FlowCell,
    FlowDoc, FlowKind, FlowPara, FlowRow, FlowTable, ZipPackage,
};
use layout_presentation_deck::model::master::{Presentation, Slide};
use layout_presentation_deck::model::shape::Shape;
use layout_presentation_deck::model::types::{LayoutId, ShapeId, SlideId, Xfrm};
use std::collections::BTreeMap;

struct PptxSlideSpec {
    title: String,
    bullets: Vec<String>,
}

impl AssetHost<'_> {
    // ------------------------------------------------------------------------
    // 2. OpenXML Prose Document (.docx) Compilation
    // ------------------------------------------------------------------------
    pub(super) fn compile_prose_docx(&mut self, a: &Args) -> Result<Value, String> {
        fields(
            a,
            &[
                "title",
                "sections",
                "paragraphs",
                "table",
                "body",
                "artifact_id",
                "id",
            ],
        )?;

        let title = a
            .get("title")
            .map(text)
            .transpose()?
            .unwrap_or("Hypermedia Prose Document");

        let mut fdoc = FlowDoc::new();
        fdoc.title = Some(title.to_string());
        fdoc.push_para(FlowPara::with_text(FlowKind::Title, title));
        let mut paragraph_count = 1usize;

        if let Some(sec_val) = a.get("sections").or_else(|| a.get("paragraphs")) {
            for item in list(sec_val)? {
                match item {
                    Value::String(s) => {
                        fdoc.push_para(FlowPara::with_text(FlowKind::Normal, s.as_str()));
                        paragraph_count += 1;
                    }
                    Value::Record(r) => {
                        if let Some(h) = r.get("heading").or_else(|| r.get("title")) {
                            if let Ok(ht) = text(h) {
                                fdoc.push_para(FlowPara::with_text(FlowKind::Heading(1), ht));
                                paragraph_count += 1;
                            }
                        }
                        if let Some(b) = r
                            .get("body")
                            .or_else(|| r.get("text"))
                            .or_else(|| r.get("content"))
                        {
                            if let Ok(bt) = text(b) {
                                fdoc.push_para(FlowPara::with_text(FlowKind::Normal, bt));
                                paragraph_count += 1;
                            }
                        }
                    }
                    _ => {}
                }
            }
        } else if let Some(body_str) = a.get("body").map(text).transpose()? {
            for line in body_str.lines() {
                fdoc.push_para(FlowPara::with_text(FlowKind::Normal, line));
                paragraph_count += 1;
            }
        } else {
            fdoc.push_para(FlowPara::with_text(
                FlowKind::Normal,
                "Generated by Hypermedia Discourse Ontology.",
            ));
            paragraph_count += 1;
        }

        if let Some(tbl_val) = a.get("table") {
            let rows = list(tbl_val)?;
            if !rows.is_empty() {
                let mut table = FlowTable::default();
                for row in rows {
                    let cells = list(row)?;
                    let mut flow_row = FlowRow::default();
                    for cell in cells {
                        let cell_txt = match cell {
                            Value::String(s) => s.as_str(),
                            _ => "",
                        };
                        flow_row.cells.push(FlowCell::with_text(cell_txt));
                    }
                    table.rows.push(flow_row);
                }
                fdoc.push_table(table);
            }
        }

        let pkg = to_docx_package(&fdoc);
        let zip_bytes = pkg.write_to_bytes();
        let parsed_pkg =
            ZipPackage::parse(&zip_bytes).map_err(|e| format!("DOCX zip parse failed: {e}"))?;
        let roundtrip = parse_docx_package(&parsed_pkg)
            .map_err(|e| format!("DOCX round-trip failed: {e}"))?;
        if roundtrip.blocks.is_empty() {
            return Err("DOCX round-trip produced empty body".into());
        }
        let byte_len = zip_bytes.len();
        self.charge(paragraph_count * 512 + 512, byte_len * 2 + 1024)?;

        let encoded = self.encode("docx", zip_bytes)?;

        let mut rec = match encoded {
            Value::Record(r) => r,
            _ => BTreeMap::new(),
        };

        let id_str = a
            .get("artifact_id")
            .or_else(|| a.get("id"))
            .and_then(|v| text(v).ok())
            .map(|s| s.to_string())
            .unwrap_or_else(|| {
                let h = rec
                    .get("handle")
                    .and_then(|v| match v {
                        Value::U64(n) => Some(*n),
                        Value::I64(n) => Some(*n as u64),
                        _ => None,
                    })
                    .unwrap_or(0);
                format!("discourse-docx-{h}")
            });

        rec.insert("id".into(), Value::String(id_str.clone()));
        rec.insert("resource".into(), Value::String(id_str));
        rec.insert("kind".into(), Value::String("docx".into()));
        rec.insert("paragraph_count".into(), Value::I64(paragraph_count as i64));
        rec.insert(
            "docx_block_count".into(),
            Value::I64(roundtrip.blocks.len() as i64),
        );
        rec.insert("byte_len".into(), Value::I64(byte_len as i64));

        Ok(Value::Record(rec))
    }

    // ------------------------------------------------------------------------
    // 3. OpenXML Presentation Deck (.pptx) Compilation
    // ------------------------------------------------------------------------
    pub(super) fn compile_deck_pptx(&mut self, a: &Args) -> Result<Value, String> {
        fields(
            a,
            &["title", "subtitle", "slides", "body", "artifact_id", "id"],
        )?;

        let title = a
            .get("title")
            .map(text)
            .transpose()?
            .unwrap_or("Hypermedia Presentation Deck");

        let mut slides: Vec<PptxSlideSpec> = Vec::new();

        if let Some(slides_val) = a.get("slides") {
            let slide_items = list(slides_val)?;
            if slide_items.is_empty() {
                return Err("slides array must not be empty".into());
            }
            if slide_items.len() > 128 {
                return Err("slides count exceeds 128".into());
            }
            for (idx, item) in slide_items.iter().enumerate() {
                let r = record(item)?;
                let s_title = r
                    .get("title")
                    .map(text)
                    .transpose()?
                    .unwrap_or(&format!("Slide {}", idx + 1))
                    .to_string();

                let mut bullets = Vec::new();
                if let Some(bullets_val) = r.get("bullets") {
                    for b in list(bullets_val)? {
                        if let Ok(t) = text(b) {
                            bullets.push(t.to_string());
                        }
                    }
                } else if let Some(b_str) = r
                    .get("subtitle")
                    .or_else(|| r.get("body"))
                    .or_else(|| r.get("content"))
                    .map(text)
                    .transpose()?
                {
                    bullets.push(b_str.to_string());
                }

                slides.push(PptxSlideSpec {
                    title: s_title,
                    bullets,
                });
            }
        } else {
            // Default 1 slide
            let mut bullets = Vec::new();
            if let Some(sub) = a.get("subtitle").map(text).transpose()? {
                bullets.push(sub.to_string());
            } else if let Some(body) = a.get("body").map(text).transpose()? {
                bullets.push(body.to_string());
            } else {
                bullets.push("Generated by Hypermedia Discourse Foliation Engine.".to_string());
            }

            slides.push(PptxSlideSpec {
                title: title.to_string(),
                bullets,
            });
        }

        let slide_count = slides.len();

        let mut pres = Presentation::default();
        for (i, slide) in slides.iter().enumerate() {
            let mut s = Slide::new(SlideId((i + 1) as u32), LayoutId(1));
            s.shapes.push(
                Shape::new(
                    ShapeId(2),
                    "Title",
                    Xfrm::new(54.0, 43.0, 612.0, 72.0),
                )
                .with_text(&slide.title),
            );
            s.shapes.push(
                Shape::new(
                    ShapeId(3),
                    "Content",
                    Xfrm::new(54.0, 126.0, 612.0, 236.0),
                )
                // One <a:p> per bullet; joining with U+000A is illegal in DrawingML a:t.
                .with_paragraphs(slide.bullets.clone()),
            );
            pres.slides.push(s);
        }

        let pkg = to_pptx_package(&pres);
        let zip_bytes = pkg.write_to_bytes();
        let parsed_pkg =
            ZipPackage::parse(&zip_bytes).map_err(|e| format!("PPTX zip parse failed: {e}"))?;
        let roundtrip = parse_pptx_package(&parsed_pkg)
            .map_err(|e| format!("PPTX round-trip failed: {e}"))?;
        if roundtrip.slides.len() != slide_count {
            return Err(format!(
                "PPTX round-trip slide count {} != {slide_count}",
                roundtrip.slides.len()
            ));
        }
        let byte_len = zip_bytes.len();
        self.charge(slide_count * 1024 + 512, byte_len * 2 + 1024)?;

        let encoded = self.encode("pptx", zip_bytes)?;

        let mut rec = match encoded {
            Value::Record(r) => r,
            _ => BTreeMap::new(),
        };

        let id_str = a
            .get("artifact_id")
            .or_else(|| a.get("id"))
            .and_then(|v| text(v).ok())
            .map(|s| s.to_string())
            .unwrap_or_else(|| {
                let h = rec
                    .get("handle")
                    .and_then(|v| match v {
                        Value::U64(n) => Some(*n),
                        Value::I64(n) => Some(*n as u64),
                        _ => None,
                    })
                    .unwrap_or(0);
                format!("discourse-pptx-{h}")
            });

        rec.insert("id".into(), Value::String(id_str.clone()));
        rec.insert("resource".into(), Value::String(id_str));
        rec.insert("kind".into(), Value::String("pptx".into()));
        rec.insert("slide_count".into(), Value::I64(slide_count as i64));
        rec.insert("byte_len".into(), Value::I64(byte_len as i64));

        Ok(Value::Record(rec))
    }
}
