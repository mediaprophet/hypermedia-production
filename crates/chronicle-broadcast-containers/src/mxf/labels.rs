pub fn element_key(item: u8, count: u8, kind: u8, number: u8) -> [u8; 16] {
    [
        0x06, 0x0E, 0x2B, 0x34, 0x01, 0x02, 0x01, 0x01, 0x0D, 0x01, 0x03, 0x01, item, count,
        kind, number,
    ]
}

const fn ul(rest: &[u8]) -> [u8; 16] {
    let mut k = [0u8; 16];
    k[0] = 0x06;
    k[1] = 0x0E;
    k[2] = 0x2B;
    k[3] = 0x34;
    let mut i = 0;
    while i < rest.len() && i < 12 {
        k[4 + i] = rest[i];
        i += 1;
    }
    k
}

